_PATTERN = re.compile(
    r"(?<![А-Яа-яЁё])(?:"
    + "|".join(
        re.escape(value) for value in sorted(_TRANSLATIONS, key=len, reverse=True)
    )
    + r")(?![А-Яа-яЁё])",
    re.IGNORECASE,
)


class LocalizedFont:
    def __init__(self, typeface):
        self._typeface = typeface

    def render(self, text, *args, **kwargs):
        return self._typeface.render(translate(text), *args, **kwargs)

    def size(self, text):
        return self._typeface.size(translate(text))

    def __getattr__(self, name):
        return getattr(self._typeface, name)


def set_language(language):
    global _language
    if language not in _LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")
    _language = language


def get_language():
    return _language


def translate(text):
    if _language != "en" or not isinstance(text, str):
        return text
    return _translate_english(text)


@functools.lru_cache(maxsize=8192)
def _translate_english(text):
    translated = _TRANSLATIONS.get(text.lower())
    if translated is not None:
        if text.isupper():
            return translated.upper()
        if text.istitle():
            return translated.title()
        return translated

    def replace(match):
        result = _TRANSLATIONS[match.group().lower()]
        if match.group().isupper():
            return result.upper()
        if match.group().istitle():
            return result.title()
        return result

    return _PATTERN.sub(replace, text)
